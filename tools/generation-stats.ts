/**
 * Writes generation-stats.md from assets/missions/stats.jsonl (one line per generation run, failures included) plus the
 * earlier runs, which were done before the recorder existed and are reconstructed from the build session's console logs.
 *   npx tsx tools/generation-stats.ts
 * Costs use Meta's published list prices, read from https://dev.meta.ai/docs/pricing-rate-limits on 2026-11-01:
 * Muse Spark 1.3 $1.25 per 1M input tokens and $4.25 per 1M output tokens; Muse Image $0.01 per image. Kokoro voices are local (free).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

interface Att { ms?: number; passed: boolean; errors: string[]; repairs: string[]; usage?: { prompt?: number; completion: number; reasoning?: number } }
interface Run { restoredFromConsoleLog?: boolean; when: string; case: string; passed: boolean; mission: string | null; totalMs?: number; attempts: Att[]; images?: number; voiceLines?: number; extraMs?: number }
const runs: Run[] = existsSync("assets/missions/stats.jsonl") ? readFileSync("assets/missions/stats.jsonl", "utf8").trim().split("\n").filter(Boolean).map(l => JSON.parse(l)) : [];

const IN = 1.25 / 1e6, OUT = 4.25 / 1e6, IMG = 0.01;
const sparkCost = (a: Att) => (a.usage ? (a.usage.prompt ?? 0) * IN + (a.usage.completion ?? 0) * OUT : 0);
const usd = (x: number) => `$${x.toFixed(3)}`;
const sec = (ms?: number) => (ms == null ? "n/a" : `${(ms / 1000).toFixed(0)} s`);
const short = (s: string) => s.replace(/\s+/g, " ").slice(0, 170);

let md = `# Mission generation statistics

Generated by \`npx tsx tools/generation-stats.ts\` on ${new Date().toLocaleDateString("en-CA")}. Failures are included on purpose: a generator that only shows its successes tells you nothing.

Costs are **estimates at Meta's published list prices** (Muse Spark 1.3: $1.25 per 1M input tokens, $4.25 per 1M output tokens, from the pricing page on 2026-11-01; Muse Image: $0.01 per image). Kokoro voices run locally and cost nothing. Actual billing is on your Meta account's usage page and may differ (credits applied, rounding).

## Runs recorded by the instrumented generator

`;
if (!runs.length) md += "_No instrumented runs yet._\n";
else {
  md += `| Case | Result | Attempts | Passed first try | Time (Spark + checks) | Time (voices + art) | Spark tokens in / out | Images | Voice lines | Est. cost |\n|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const r of runs) {
    const unknownIn = r.attempts.some(x => x.usage?.prompt === undefined), pin = r.attempts.reduce((a, x) => a + (x.usage?.prompt ?? 0), 0), pout = r.attempts.reduce((a, x) => a + (x.usage?.completion ?? 0), 0);
    const cost = r.attempts.reduce((a, x) => a + sparkCost(x), 0) + (r.images ?? 0) * IMG;
    md += `| ${r.case} | ${r.passed ? "passed" : "**FAILED**"} | ${r.attempts.length} | ${r.attempts[0]?.passed ? "yes" : "no"} | ${sec(r.totalMs)} | ${sec(r.extraMs)} | ${unknownIn ? "n/a" : pin} / ${pout} | ${r.images ?? 0} | ${r.voiceLines ?? 0} | ${usd(cost)}${unknownIn ? " (partial)" : ""} |\n`;
  }
  const passed = runs.filter(r => r.passed).length, first = runs.filter(r => r.attempts[0]?.passed).length;
  md += `\n**${runs.length} runs: ${passed} passed, ${runs.length - passed} failed; ${first} passed on the first attempt.**\n`;
  md += `\n### What happened in each run\n`;
  for (const r of runs) {
    md += `\n#### ${r.case} (${r.when?.slice(0, 16).replace("T", " ")} UTC): ${r.passed ? "passed" : "FAILED"}\n`;
    r.attempts.forEach((a, i) => {
      md += `- Attempt ${i + 1} (${sec(a.ms)}, ${a.usage ? `${a.usage.prompt ?? "n/a"} in / ${a.usage.completion} out tokens` : "tokens not recorded"}): ${a.passed ? "**passed every check**" : "rejected"}.\n`;
      for (const e of a.errors) md += `  - rejection: ${short(e)}\n`;
      for (const x of a.repairs) md += `  - code repair applied: ${short(x)}\n`;
    });
  }
}
md += `
## Earlier runs (before the recorder existed)

Reconstructed from the console output of the build session on 2026-11-01, case \`gallery1990\`. Times and token counts were not recorded. These are what taught the generator its checks, so they are listed in order. Each was a real Muse Spark call.

| # | What the generator had at the time | Attempts | Result | Rejection reasons, from the console |
|---|---|---|---|---|
| 1 | Model also had to get the guard's patrol balanced | 3 | FAILED | Careful player won 0% in two attempts; reckless player won cleanly 100% in two. The model cannot balance by reading text |
| 2 | Code tunes the guard's schedule; the "cautious" bot needs total silence to move | 3 | FAILED | "Too hard even after tuning": careful player 0% in all three. (Later found to be partly my simulated player: it never moved in a small building) |
| 3 | Added the "careful" bot, the narration and lore-voice checks, the single-corridor rejection | 3 | FAILED | Attempt 1: evidence tape and a room line written as narration. Attempt 2: too hard, 0%. Attempt 3: evidence tape as narration again |
| 4 | Same (second run) | 3 | FAILED | "Too hard even after tuning", 0% in all three. Offline analysis of the saved specs then showed most were a single corridor with the guard sweeping it, which led to the hub rule and to letting the code choose the guard post |
| 5 | Hub rule, code chooses the guard post, careful bot | 1 | passed, first try | none |
| 6 | Added the check that a lore answer must name its subject | 2 | passed, second try | Attempt 1: evidence tape written as narration ("Silas is speaking low and fast...") |

Totals for these six runs: 15 attempts, 2 runs passed (the last two), 4 runs failed outright. Counting is from the session's console output; the stats recorder was added after run 6.

## Honest reading

- **One rejection was my own bug.** The first Louvre run's second attempt was rejected because my lore check only accepted a character's full name or surname, and the model wrote the guard's first name ("Eddie walks with keys jingling…"). That is a false rejection by the checker, found by reading these stats, fixed, and covered by a test. The Louvre case was then re-run (the second Louvre line above).
- The model alone does not produce a playable, fair level. It produces a plausible building and good story text; code has to build the level, repair the guard's schedule and reject what is structurally unfair. That is the design, and these numbers are the evidence for it.
- Most rejections were structural (corridors, balance) and narration (a line written about the speaker, not by them). Real-name leaks were rare; the real-name check is a ban list, so it catches only the names I listed.
- Balance is judged by simulated players, not people.
`;
writeFileSync("generation-stats.md", md);
console.log(`wrote generation-stats.md (${runs.length} instrumented runs)`);
