/**
 * Runs every stress layer and writes stress-results.md.
 *   npx tsx tools/stress.ts            # scale 1 (about a minute)
 *   STRESS_SCALE=5 npx tsx tools/stress.ts
 * No network, no model calls. A finding means something broke; the report lists it with how to reproduce.
 */
import { writeFileSync, existsSync, readFileSync } from "node:fs";
import { engineFuzz, generatorFuzz, parserFuzz, pipelineFuzz, relayLoad, loadLevels, type LayerResult } from "./stress-lib";

const scale = Number(process.env.STRESS_SCALE ?? 3);
const layers: [string, (s: number) => Promise<LayerResult>][] = [["engine", engineFuzz], ["pipeline", pipelineFuzz], ["parser", parserFuzz], ["generator", generatorFuzz], ["relay", relayLoad]];
const results: LayerResult[] = [];
for (const [name, fn] of layers) {
  process.stdout.write(`${name}… `);
  const r = await fn(scale); results.push(r);
  console.log(`${r.checks} checks, ${r.findings.length} finding(s), ${(r.ms / 1000).toFixed(1)} s`);
  for (const n of r.notes) console.log(`   ${n}`);
  for (const f of r.findings.slice(0, 5)) console.log(`   FINDING: ${f.what}${f.repro ? `  [${f.repro.slice(0, 160)}]` : ""}`);
}
const total = results.reduce((a, r) => a + r.findings.length, 0);
// the findings history (what stress testing found and fixed, and what it did not cover) is written by hand in stress-history.md
const HIST = existsSync("tools/stress-history.md") ? "\n" + readFileSync("tools/stress-history.md", "utf8") : "";
const live = HIST + (existsSync("stress-live.md") ? readFileSync("stress-live.md", "utf8") : "");
const md = `# Stress test results

Generated by 'npx tsx tools/stress.ts' (scale ${scale}) on ${new Date().toLocaleDateString("en-CA")}, against ${loadLevels().length} levels: the built-in mission and ${loadLevels().length - 1} generated ones. No network and no model calls in this part. Each layer tries to break one promise the game makes.

| Layer | What it attacks | Checks | Findings | Time |
|---|---|---|---|---|
${results.map(r => `| ${r.layer} | ${{ "engine fuzz": "the rules: random and junk actions, invariants after every step, determinism, replay, finished runs", "pipeline fuzz": "speech to action: a hostile model (garbage, pollution keys, huge or late or wrong-turn replies, throws) and hostile text, with racing orders", "parser fuzz": "awkward text: very long, repeated, unicode, nulls; looking for crashes and slowdowns", "generator fuzz": "mission builder: broken and random specs; every accepted mission must be winnable", "relay load": "the Seer relay: real sockets, floods, junk, oversize, bad joins, abrupt drops" }[r.layer]} | ${r.checks} | ${r.findings.length} | ${(r.ms / 1000).toFixed(1)} s |`).join("\n")}

**${total} finding(s) in this run.**

## Details
${results.map(r => `### ${r.layer}\n${r.notes.map(n => `- ${n}`).join("\n")}\n${r.findings.length ? r.findings.map(f => `- **FINDING** ${f.what}${f.repro ? ` (repro: \`${f.repro.slice(0, 200).replace(/`/g, "'")}\`)` : ""}`).join("\n") : "- no findings"}\n`).join("\n")}
${live}`;
writeFileSync("stress-results.md", md);
console.log(`\n${total} finding(s). wrote stress-results.md`);
process.exit(total ? 1 : 0);
