/**
 * Balance simulator. Plays N seeded runs per policy through the real engine and reports outcomes.
 * Policies only act on what Marlow PERCEIVES (event stream + her knowledge), never on the hidden guard position.
 *   cautious: listen, move only after a silent listen, otherwise wait (or hide when warned and cover exists)
 *   reckless: always move toward the objective
 * Usage: npx tsx tools/simulate.ts [seeds=1000] [--md]   -> simulation.md + simulation.svg
 */
import { writeFileSync } from "node:fs";
import { POLICIES, summarize } from "./sim-core";
import { level as baseLevel } from "./lib";

const routeArg = process.argv.find(a => a.startsWith("--route="))?.slice(8);
const level = routeArg ? { ...baseLevel, guard: { ...baseLevel.guard, route: routeArg.split(",") } } : baseLevel;

const NN = Number(process.argv.find(a => /^\d+$/.test(a)) ?? 1000);
const EXPERT_N = Math.min(NN, Number(process.env.EXPERT_N ?? 300));
const rows = summarize(level, [...POLICIES, "expert"], NN, EXPERT_N);
console.table(rows);

const today = new Date().toLocaleDateString("en-CA"); // local date, YYYY-MM-DD
const alarmN = (baseLevel as { objective: { alarmTurns?: number } }).objective.alarmTurns;
let sweepMd = "";
if (process.argv.includes("--sweep")) {
  const Ns = [6, 8, 10, 12, 16, 20], SW = Math.min(NN, 400), SWE = Math.min(SW, 60);
  const lines: string[] = [];
  for (const n of Ns) {
    const lv = { ...level, objective: { ...(level as { objective: object }).objective, alarmTurns: n } };
    const r = summarize(lv, [...POLICIES, "expert"], SW, SWE);
    lines.push(`| ${n} | ` + r.map(x => `${x.win} / ${x.cleanWin}`).join(" | ") + " |");
  }
  sweepMd = `
## How the silent alarm's length changes everything

Same level, same guard; only alarmTurns (moves allowed after the ledger is taken) changes. Each cell is win % / clean-win % (${SW} seeded runs per policy, expert ${SWE}). Measured ${today}.

| alarmTurns | ${[...POLICIES, "expert"].join(" | ")} |
|---|${[...POLICIES, "expert"].map(() => "---").join("|")}|
${lines.join("\n")}

Reading it: with any alarm up to 16 moves, a player who keeps waiting for the guard to leave (waiter, cautious, cautious-no-cover) is caught every time, because after the take the alarm, not the guard, is the clock. A player who moves quietly and decisively (careful, expert) still wins. The shipped value is ${alarmN}. One oddity worth stating: careful's clean-win rate goes 100, 0, 0, 0, 100, 100 as the alarm lengthens. The simulation is deterministic (the guard's start is fixed), so that is not noise: the alarm-aware rule changes the turn at which careful decides to leave, and whether that turn happens to coincide with the guard's patrol decides if it is seen. It shows how sensitive a fixed patrol is to timing, which is part of what a variable start would smooth out.
`;
}
const md = `# Balance simulation

Generated by 'npx tsx tools/simulate.ts' on ${today}: ${NN} seeded runs per policy (expert: ${EXPERT_N}), real engine, silent alarm length ${alarmN ?? "none"} moves. Every policy sees only what Marlow perceives, never the guard's hidden position. These are measurements of simple simulated players, not of people, and they are not tuned to hit any target.

| Policy | Win % | Clean win % (alert ≤ 1) | Caught % | Timeout (60 turns) % | Mean turns to win | Mean final trust |
|---|---|---|---|---|---|---|
${rows.map(r => `| ${r.policy} | ${r.win} | ${r.cleanWin} | ${r.caught} | ${r.timeout} | ${r.meanTurnsToWin ?? "n/a"} | ${r.meanTrust} |`).join("\n")}

What each policy does:
- **reckless**: always moves toward the objective, never listens.
- **careful**: listens; moves quietly unless footsteps are near or in the direction it is heading; hides or steps away when warned; once the silent alarm is running and time is short, stops waiting and goes, quietly.
- **cautious**: listens and moves only after a silent listen; hides on a warning; ignores the alarm. (The earlier published cautious player; kept unchanged so numbers stay comparable.)
- **cautious-no-cover**: cautious without hiding on a warning.
- **waiter**: the most timid player. Listens; moves only after a silent listen; whenever unsure it waits. Never hides, ignores the alarm.
- **expert**: knows the rules and that the guard walks a loop; tracks which route positions are consistent with what it has perceived and looks 3 turns ahead.

Win % counts any exit (one sighting, alert 2, is survivable; alert 3 or the alarm reaching zero is caught). **Clean win** (alert ≤ 1) is the skill measure.

What the numbers say, plainly: the guard's start is fixed (he is upstairs for three turns), so a player who rushes always gets out, but never cleanly. The silent alarm means waiting stops being a strategy once the ledger is taken. The fixed opening makes a first run learnable but also makes the simulated players' results the same on every seed; a variable start would add variety at the cost of an easier-to-learn first run.
${sweepMd}`;
if (!routeArg) writeFileSync("simulation.md", md);
const bar = (y: number, label: string, v: number, color: string) => `<text x="10" y="${y + 14}" fill="#ccd" font-size="13" font-family="sans-serif">${label}</text><rect x="150" y="${y}" width="${v * 4}" height="20" fill="${color}"/><text x="${156 + v * 4}" y="${y + 15}" fill="#fff" font-size="13" font-family="sans-serif">${v}%</text>`;
if (!routeArg) writeFileSync("simulation.svg", `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 620 ${40 + rows.length * 56}" role="img" aria-label="Win rate by player policy"><rect width="100%" height="100%" fill="#0b0b10"/><text x="10" y="22" fill="#e8a33d" font-size="16" font-family="serif">Win rate over seeded runs</text>${rows.map((r, i) => bar(36 + i * 56, `${r.policy} (win)`, r.win, "#e8a33d") + bar(58 + i * 56 - 2, `${r.policy} (caught)`, r.caught, "#c33")).join("")}</svg>`);
